import { wrapInEmailLayout } from "../layout";
import { renderParagraph, renderDetailRows, renderButton, renderMuted } from "../components";
import { formatLkr } from "../utils";

export interface ClientInvoiceEmailData {
  invoiceNumber: string;
  businessName: string;
  clientName?: string;
  amount: number | string;
  dueDate: string;
  viewInvoiceUrl: string;
  notes?: string;
  isFreePlan?: boolean;
}

export function buildClientInvoiceEmail({
  invoiceNumber,
  businessName,
  clientName,
  amount,
  dueDate,
  viewInvoiceUrl,
  notes,
  isFreePlan = false,
}: ClientInvoiceEmailData): {
  subject: string;
  html: string;
  text: string;
} {
  const formattedAmount = formatLkr(amount);
  const cleanBusiness = businessName?.trim() || "Your vendor";
  const subject = `Invoice ${invoiceNumber} from ${cleanBusiness}`;
  const preheader = `Due ${dueDate} — ${formattedAmount}`;

  const greeting = clientName?.trim() ? `Hi ${clientName.trim()},` : "Hi,";

  const rows = [
    { label: "Invoice number", value: invoiceNumber },
    { label: "Amount due", value: formattedAmount, isBold: true },
    { label: "Due date", value: dueDate },
  ];

  const notesBlock = notes?.trim() ? renderMuted(`Note: ${notes.trim()}`) : "";

  const contentHtml = `
    ${renderParagraph(greeting)}
    ${renderParagraph(`${cleanBusiness} has sent you invoice ${invoiceNumber} for ${formattedAmount}, due on ${dueDate}.`)}
    ${renderDetailRows(rows)}
    ${renderButton("View and pay invoice", viewInvoiceUrl)}
    ${notesBlock}
    ${renderParagraph("If you have questions about this invoice, reply directly to this email to reach the vendor.")}
    ${renderParagraph(cleanBusiness, true)}
  `;

  const html = wrapInEmailLayout({
    preheader,
    contentHtml,
    businessSenderName: cleanBusiness,
    isClientInvoice: true,
    isFreePlan,
    showLogo: !isFreePlan, // Use vendor context
  });

  const text = `${cleanBusiness}

${greeting}

${cleanBusiness} has sent you invoice ${invoiceNumber} for ${formattedAmount}, due on ${dueDate}.

Invoice: ${invoiceNumber}
Amount due: ${formattedAmount}
Due date: ${dueDate}

View invoice: ${viewInvoiceUrl}
${notes?.trim() ? `\nNote: ${notes.trim()}\n` : ""}
If you have questions about this invoice, reply directly to this email to reach the vendor.

${cleanBusiness}
--
Sent by ${cleanBusiness} via Framebooks.
${isFreePlan ? "Generated by Framebooks" : ""}`;

  return { subject, html, text };
}
